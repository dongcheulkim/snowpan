export function searchSupportAnswer(content: string): string | null {
  const text = content.trim();
  if (text.length < 4 || text.startsWith('[문의]')) return null;
  const norm = text.toLowerCase();
  const compact = norm.replace(/\s+/g, '');
  let bestKey: string | null = null; let bestScore = 0;
  for (const [key, words] of Object.entries(KEYWORDS)) {
    // 맞은 키워드의 글자 수 합 (긴 키워드가 더 확실). '안 돼요'/'안돼요'처럼 같은 말의 변형은 한 번만 센다.
    const hit = new Set<string>();
    for (const w of words) {
      const wc = w.toLowerCase().replace(/\s+/g, '');
      if (norm.includes(w.toLowerCase()) || compact.includes(wc)) hit.add(wc);
    }
    let score = 0;
    for (const h of hit) if (![...hit].some((o) => o !== h && o.includes(h))) score += h.length;
    if (score > bestScore) { bestScore = score; bestKey = key; } // 동점이면 먼저 정의된(더 구체적인) 항목 유지
  }
  if (!bestKey || bestScore < 2) return null;
  const answer = ANSWERS[bestKey];
  if (!answer) return null;
  const topic = bestKey.split(' > ')[1];
  return `혹시 "${topic}" 관련 문의라면 먼저 이 안내를 확인해 주세요.\n\n${answer}\n\n다른 내용이면 그대로 두세요. 담당자가 확인하고 이어서 답해 드려요.`;
}
