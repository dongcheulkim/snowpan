// "[문의] 카테고리 > 세부" 메시지에서 답을 찾는다. 없으면 null (사람이 답함).
export function findSupportAnswer(content: string): string | null {
  const m = content.trim().match(/^\[문의\]\s*(.+?)\s*>\s*(.+)$/);
  if (!m) return null;
  const key = `${m[1].trim()} > ${m[2].trim()}`;
  const answer = ANSWERS[key];
  if (!answer) return null;
  return `${answer}\n\n더 궁금한 점은 여기에 바로 적어 주세요. 담당자가 이어서 답해 드려요.`;
}
